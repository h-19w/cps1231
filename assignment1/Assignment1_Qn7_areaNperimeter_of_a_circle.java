public class Assignment1_Qn7_areaNperimeter_of_a_circle {
    public static void main(String[] args) {
        double pi = 3.1415926;
        double radius = 6.5;
        double perimeter = 2*radius*pi;
        double area = radius*radius*pi;
        System.out.println("The area of a circle with radius 6.5 is :"+ area);
        System.out.println("The perimeter of a circle with radius 6.5 is :"+ perimeter);
    }
}