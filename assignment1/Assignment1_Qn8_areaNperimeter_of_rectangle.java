
public class Assignment1_Qn8_areaNperimeter_of_rectangle {
    public static void main(String[] args) {
        double width = 5.3;
        double height = 8.6;
        double area = width * height;
        double perimeter = 2 * (width+height);
        System.out.println("The area of a rectangle with a width of 5.3 and height of 8.6 is : "+ area);
        System.out.println("The perimeter of a rectangle a width of 5.3 and height of 8.6 is : "+ perimeter);
    }
}